"""Build optimized lobby artwork and an R2-ready asset manifest.

Run from the repository root with Pillow available. Original generated source
images stay in the local work directory; the website ships only WebP derivatives.
"""
from pathlib import Path
from PIL import Image, ImageOps
import argparse
import hashlib
import json
import re
import shutil
import zipfile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'lobby/assets'
SCRATCH = ROOT / 'work/art-source'
HERO_SOURCE = ROOT.parent / 'hero-art'
REUSED = {
    'apestogetherstrong': 'apestogetherstrong.png',
    'ironthrone': 'iron_thrones.png',
    'cat': 'cat and mouse.png',
    'grass': 'grass realms.png',
    'warrealms': 'warrealms.png',
    'trials': 'emojisquad.png',
    'arcanewilds': 'arcanewilds.png',
    'spacetyrants': 'space_tyrants.png',
    'chrisrunner': 'chrisrunner.png',
    'chesswarlord': 'chess warlord.png',
    'turncraft': 'turncraft-lobby.webp',
    'crowncouncil': '../../lobby/assets/faction-forge-lobby.webp',
}

def editorial_tiers():
    code = (ROOT / 'lobby/lobby-showcase.js').read_text(encoding='utf8')
    groups = {}
    for group in ['flagships', 'premium', 'builtOut', 'experimental', 'tools']:
        match = re.search(r'\b' + group + r':\s*Object\.freeze\(\[([\s\S]*?)\]\)', code)
        if not match:
            raise ValueError(f'Missing editorial configuration: {group}')
        block = match.group(1)
        groups[group] = set(re.findall(r"\bkey:\s*['\"]([^'\"]+)['\"]", block)) if 'key:' in block else set(re.findall(r"['\"]([^'\"]+)['\"]", block))
    return groups

def tier_for(game, groups):
    key = game['key']
    if key in groups['flagships']:
        return 'flagship'
    if key in groups['premium']:
        return 'showcase'
    if key in groups['builtOut']:
        return 'built-out'
    if key in groups['tools']:
        return 'tool'
    if key in groups['experimental'] or 'Incomplete' in game['title']:
        return 'experimental'
    return 'in-production'

def save_manifest(manifest):
    serialized = json.dumps(manifest, indent=2, ensure_ascii=False)
    (ASSETS / 'game-artwork.json').write_text(serialized + '\n', encoding='utf8')
    (ASSETS / 'game-artwork.js').write_text('// Generated by tooling/build-lobby-artwork.py.\n(function(root){root.GameHubArtworkManifest=' + serialized + ';})(typeof globalThis!=="undefined"?globalThis:this);\n', encoding='utf8')

def derivative(source, destination, width, quality, preserve_whole=False):
    with Image.open(source) as original:
        image = ImageOps.exif_transpose(original).convert('RGB')
        size = (width, round(width * 9 / 16))
        # Existing title art includes painted lettering; letterbox instead of
        # cropping words or changing the original illustration. New covers use
        # a protected central composition and a conventional landscape crop.
        if preserve_whole:
            image = ImageOps.pad(image, size, method=Image.Resampling.LANCZOS, color='#101622')
        else:
            image = ImageOps.fit(image, size, method=Image.Resampling.LANCZOS)
        destination.parent.mkdir(parents=True, exist_ok=True)
        image.save(destination, 'WEBP', quality=quality, method=6)
    data = destination.read_bytes()
    return {'width': size[0], 'height': size[1], 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}

def build(source_map):
    registry = json.loads((SCRATCH / 'registry.json').read_text(encoding='utf8'))
    generated = {entry['key']: entry for entry in json.loads(source_map.read_text(encoding='utf8'))}
    groups = editorial_tiers()
    flagships = groups['flagships']
    manifest = {'version': 2, 'basePath': '/lobby/assets/', 'generatedWith': 'built-in imagegen', 'format': 'WebP', 'aspectRatio': '16:9', 'sizes': {'tile': 640, 'thumb': 240, 'hero': 1280}, 'fallback': 'game-tiles/arcade-fallback.webp', 'games': {}, 'files': {}, 'interfaceFiles': {}}
    for game in registry:
        key = game['key']
        reused = key in REUSED
        source = (SCRATCH / REUSED[key]).resolve() if reused else Path(generated[key]['path']) if key in generated else None
        if source and not source.exists():
            raise FileNotFoundError(source)
        entry = dict(game)
        entry['tier'] = tier_for(game, groups)
        entry['provenance'] = 'reused-existing-artwork' if reused else 'original-built-in-imagegen'
        entry['sourceArtwork'] = 'https://pub-cb55798f1eeb4f80a85463da3612ed61.r2.dev/effects/ui/turncraft-lobby.webp' if key == 'turncraft' else game['originalImagePath'] if reused else Path(generated[key]['path']).name if key in generated else None
        entry['tile'] = f'game-tiles/{key}.webp'
        entry['thumb'] = f'game-thumbnails/{key}.webp'
        entry['hero'] = f'game-heroes/{key}.webp' if key in flagships else entry['tile']
        entry['ready'] = source is not None
        if key in flagships and (HERO_SOURCE / f'{key}.webp').exists():
            entry['heroProvenance'] = 'original-built-in-imagegen'
        manifest['games'][key] = entry
        if source:
            for kind, width, quality in [('tile', 640, 79), ('thumb', 240, 72)] + ([('hero', 1280, 83)] if key in flagships else []):
                relative = entry[kind]
                hero = HERO_SOURCE / f'{key}.webp'
                if kind == 'hero' and hero.exists():
                    target = ASSETS / relative
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(hero, target)
                    data = target.read_bytes()
                    with Image.open(target) as im:
                        manifest['files'][relative] = {'width': im.width, 'height': im.height, 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}
                else:
                    manifest['files'][relative] = derivative(source, ASSETS / relative, width, quality, reused and key not in {'turncraft', 'crowncouncil'})
    if 'arcade-fallback' in generated:
        source = Path(generated['arcade-fallback']['path'])
        manifest['files']['game-tiles/arcade-fallback.webp'] = derivative(source, ASSETS / 'game-tiles/arcade-fallback.webp', 640, 78)
    code = (ROOT / 'lobby/lobby-flagships.js').read_text(encoding='utf8')
    sprite_defs = re.search(r'<svg width="0" height="0" class="cnm-sprite-defs">(.*?)</svg>', code, re.S).group(1)
    sprite = '<svg xmlns="http://www.w3.org/2000/svg" width="144" height="40" viewBox="0 0 144 40" role="img" aria-label="Original Cat N Mice arcade silhouettes">' + sprite_defs + '<use href="#cnm-mouse" x="0" y="4" width="48" height="32" color="#65e5dc"/><use href="#cnm-cat" x="76" y="0" width="64" height="40" color="#eeae83"/></svg>\n'
    pathways = re.search(r'<svg class="cnm-pathways".*?</svg>', code, re.S).group()
    pathways = pathways.replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" width="1440" height="900" fill="none" stroke="#25d4d0" stroke-width="1.5" ', 1) + '\n'
    for relative, content in [('interface/cat-mouse-sprites.svg', sprite), ('interface/arcade-pathways.svg', pathways)]:
        path = ASSETS / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf8')
        data = path.read_bytes()
        manifest['interfaceFiles'][relative] = {'format': 'SVG', 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest(), 'provenance': 'original-native-vector', 'runtime': 'Inline copies use transform and opacity; no extra image requests.'}
    ASSETS.mkdir(parents=True, exist_ok=True)
    save_manifest(manifest)
    prompts = [{'key': item['key'], 'prompt': item.get('prompt', 'Original Hearthmouse kitchen survival key art; full prompt documented in docs/arcade-nexus-artwork.md.')} for item in generated.values()]
    (ASSETS / 'generation-prompts.json').write_text(json.dumps(prompts, indent=2, ensure_ascii=False) + '\n', encoding='utf8')
    if (HERO_SOURCE / 'hero-prompts.json').exists():
        shutil.copy2(HERO_SOURCE / 'hero-prompts.json', ASSETS / 'hero-prompts.json')
    print(json.dumps({'registeredGames': len(registry), 'ready': sum(g['ready'] for g in manifest['games'].values()), 'reused': len(REUSED), 'newArt': len(generated), 'webpFiles': len(manifest['files']), 'webpBytes': sum(f['bytes'] for f in manifest['files'].values())}))
    return manifest

def verify(manifest):
    errors = []
    for key, game in manifest['games'].items():
        if not game.get('ready'):
            errors.append(f'{key}: artwork is incomplete')
        for variant in ['tile', 'thumb', 'hero']:
            if game[variant] not in manifest['files']:
                errors.append(f'{key}: unlisted {variant} artwork')
    if manifest['fallback'] not in manifest['files']:
        errors.append('Missing dynamic-game fallback')
    for relative, recorded in manifest['files'].items():
        path = (ASSETS / relative).resolve()
        if not path.is_relative_to(ASSETS.resolve()):
            errors.append(f'Invalid asset path: {relative}')
            continue
        if not path.exists():
            errors.append(f'Missing file: {relative}')
            continue
        data = path.read_bytes()
        if len(data) != recorded['bytes'] or hashlib.sha256(data).hexdigest() != recorded['sha256']:
            errors.append(f'Content mismatch: {relative}')
        with Image.open(path) as im:
            if im.format != 'WEBP' or im.size != (recorded['width'], recorded['height']):
                errors.append(f'Image format/dimension mismatch: {relative}')
            im.verify()
    for relative, recorded in manifest.get('interfaceFiles', {}).items():
        path = (ASSETS / relative).resolve()
        if not path.is_relative_to(ASSETS.resolve()) or not path.exists():
            errors.append(f'Invalid or missing interface asset: {relative}')
            continue
        data = path.read_bytes()
        if len(data) != recorded['bytes'] or hashlib.sha256(data).hexdigest() != recorded['sha256']:
            errors.append(f'Interface content mismatch: {relative}')
        ET.fromstring(data)
    if errors:
        raise SystemExit('\n'.join(errors))
    print(json.dumps({'verifiedGames': len(manifest['games']), 'verifiedWebPFiles': len(manifest['files']), 'verifiedBytes': sum(f['bytes'] for f in manifest['files'].values())}))

def package(manifest, destination):
    verify(manifest)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(destination, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
        for relative in manifest['files']:
            archive.write(ASSETS / relative, relative)
        for relative in manifest.get('interfaceFiles', {}):
            archive.write(ASSETS / relative, relative)
        for name in ['game-artwork.json', 'game-artwork.js', 'generation-prompts.json', 'hero-prompts.json']:
            if (ASSETS / name).exists():
                archive.write(ASSETS / name, name)
    print(str(destination.resolve()))

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--source-map', type=Path)
    parser.add_argument('--source-dir', type=Path, default=SCRATCH)
    parser.add_argument('--hero-source', type=Path, default=HERO_SOURCE)
    parser.add_argument('--verify', action='store_true', help='Verify committed artwork without generation sources.')
    parser.add_argument('--package-only', action='store_true', help='Package committed artwork without generation sources.')
    parser.add_argument('--refresh-metadata', action='store_true', help='Refresh editorial tiers without changing artwork files.')
    parser.add_argument('--zip', type=Path)
    args = parser.parse_args()
    SCRATCH = args.source_dir
    HERO_SOURCE = args.hero_source
    manifest = json.loads((ASSETS / 'game-artwork.json').read_text(encoding='utf8')) if args.verify or args.package_only or args.refresh_metadata else build(args.source_map or SCRATCH / 'generated-current.json')
    if args.refresh_metadata:
        groups = editorial_tiers()
        for entry in manifest['games'].values():
            entry['tier'] = tier_for(entry, groups)
        manifest['editorialSource'] = 'lobby/lobby-showcase.js'
        save_manifest(manifest)
    if args.verify:
        verify(manifest)
    if args.zip:
        package(manifest, args.zip)
    elif args.package_only:
        parser.error('--package-only requires --zip DESTINATION')
