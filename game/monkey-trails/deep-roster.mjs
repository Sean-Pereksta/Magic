export const hosts = ['bridgeback', 'nacreon', 'orrakai'];
export const deepSpecies = rows.map(([name, region, elements, move, title, desc, effect, depth], i) => {
  const id = name.toLowerCase(),
    types = elements.split(' '),
    signature = move.replace(/ /g, '');
  return {
    id,
    name,
    region,
    types,
    title,
    signature,
    desc,
    rarity: depth ? 'mythic' : 'ultra',
    minFeet: depth || { [REEF]: 30000, [LOOM]: 45000, [GLASS]: 65000 }[region],
    role: effect.guard ? 'defender' : i === 1 ? 'healer' : 'attacker',
    hp: 100 + (i % 4) * 4,
    atk: 15 + (i % 3),
    def: 12 + (i % 4),
    speed: 8 + (i % 5),
    move: {
      name: move,
      deep: id,
      owner: id,
      family: 'signature',
      signature: true,
      type: types[0],
      cost: 5,
      cooldown: 3,
      desc,
      ...effect,
    },
  };
});
export function registerDeep(species, moves) {
  for (const row of deepSpecies) {
    const { move, ...p } = row;
    moves[p.signature] = move;
    species[p.id] = {
      ...p,
      number: Object.keys(species).length + 1,
      affinity: p.types.join(' / '),
      expansion: 4,
      habitat: 'landmark',
      habitats: ['landmark'],
      trait: p.desc,
      appearance: p.title + '. ' + p.desc,
      signature: p.signature,
      specialty: p.signature,
      learnset: [
        'strike',
        'brace',
        'breathe',
        p.signature,
        ...p.types.map(
          (t) =>
            ({
              water: 'tide',
              storm: 'spark',
              leaf: 'seedDrain',
              ice: 'icicleBurst',
              shadow: 'nightDrain',
              earth: 'stonePalm',
              fire: 'flare',
              light: 'dawnPalm',
            })[t],
        ),
      ],
      encounterWeight: 0,
      captureChance: 1,
      evolutionAppearances: ['Elemental mantle', 'Layered crest', 'Mastery crown'],
    };
  }
}
