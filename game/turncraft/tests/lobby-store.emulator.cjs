'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
const {initializeTestEnvironment, assertFails, assertSucceeds} = require('@firebase/rules-unit-testing');
const api = require('firebase/firestore');
(async () => {
  if (!process.env.FIRESTORE_EMULATOR_HOST) throw new Error('Run through the local Firebase emulator.');
  const {createLobbyStore, completeCustomMatch} = await import(pathToFileURL(path.resolve(__dirname, '../shattered-front/lobby-store.mjs')).href);
  const env = await initializeTestEnvironment({projectId: 'demo-turncraft', firestore: {rules: fs.readFileSync(path.resolve(__dirname, '../../../firestore.rules'), 'utf8')}});
  try {
    await env.clearFirestore();
    await env.withSecurityRulesDisabled(async context => {
      await api.setDoc(api.doc(context.firestore(), 'users', 'Owner'), {ownerUid: 'owner', gameStats: {turncraft: {mmr: 1500, rankedMatches: 10}, otherGame: {wins: 9}}});
      await api.setDoc(api.doc(context.firestore(), 'users', 'Peer'), {ownerUid: 'peer', gameStats: {turncraft: {mmr: 1000, rankedMatches: 0}}});
    });
    const ownerDb = env.authenticatedContext('owner').firestore(), peerDb = env.authenticatedContext('peer').firestore(), strangerDb = env.authenticatedContext('stranger').firestore();
    const ownerAuth = {currentUser: {uid: 'owner'}}, peerAuth = {currentUser: {uid: 'peer'}};
    const owner = createLobbyStore({db: ownerDb, auth: ownerAuth, api, getIdentity: () => ({uid: 'owner', username: 'Owner'})});
    const peer = createLobbyStore({db: peerDb, auth: peerAuth, api, getIdentity: () => ({uid: 'peer', username: 'Peer'})});
    const stranger = createLobbyStore({db: strangerDb, auth: {currentUser: {uid: 'stranger'}}, api, getIdentity: () => ({uid: 'stranger', username: 'Stranger'})});

    const room = await owner.create({requestId: 'direct-public', name: 'Direct Firestore', settings: {maxPlayers: 2}});
    assert.equal(room.turncraftPlayers.owner.mmr, 1500);
    assert.equal((await owner.create({requestId: 'direct-public'})).id, room.id);
    assert.equal((await peer.browse()).lobbies[0].id, room.id);
    await assertFails(api.getDoc(api.doc(strangerDb, 'turncraftLobbySecrets', room.id)));
    await assertFails(api.getDocs(api.collection(strangerDb, 'turncraftInvites')));
    await assertFails(api.updateDoc(api.doc(strangerDb, 'lobbies', room.id), {hostUid: 'stranger'}));
    await peer.join({lobbyId: room.id});
    await assert.rejects(peer.start(room.id), {code: 'HOST_ONLY'});
    await assert.rejects(owner.start(room.id), {code: 'NOT_READY'});
    await assert.rejects(stranger.join({lobbyId: room.id}), {code: 'LOBBY_FULL'});
    await assertFails(api.updateDoc(api.doc(peerDb, 'lobbies', room.id), {'turncraftPlayers.owner.ready': true}));
    await assertFails(api.updateDoc(api.doc(ownerDb, 'lobbies', room.id), {ranked: true}));
    await owner.player(room.id, {ready: true});
    await peer.player(room.id, {factionId: 'brood', ready: true});
    await owner.configure(room.id, {settings: {maxPlayers: 2, mapId: 'ember-rift'}});
    assert.ok(Object.values((await owner.get(room.id)).turncraftPlayers).every(player => !player.ready));
    await owner.player(room.id, {ready: true}); await peer.player(room.id, {ready: true});
    const started = await owner.start(room.id);
    assert.equal(started.status, 'started'); assert.equal(started.chessStarfrontReady.Peer.factionId, 'brood');
    await assert.rejects(stranger.join({lobbyId: room.id}), {code: 'MATCH_STARTED'});
    await assertFails(api.updateDoc(api.doc(peerDb, 'lobbies', room.id), {settings: {...started.settings, mapId: 'classic'}}));

    const lease = {ownerUid: 'owner', ownerName: 'Owner', epoch: 1, expiresAtMs: Date.now() + 16000};
    await api.updateDoc(api.doc(ownerDb, 'lobbies', room.id), {chessStarfrontController: lease, updatedAt: api.serverTimestamp()});
    await assertFails(api.updateDoc(api.doc(peerDb, 'lobbies', room.id), {chessStarfrontController: {...lease, ownerUid: 'peer', ownerName: 'Peer', epoch: 2}}));
    await assert.rejects(completeCustomMatch({db: ownerDb, auth: ownerAuth, api}, room.id), {code: 'RESULT_NOT_READY'});
    const finalState = {gameKey: 'chess_starfront', gameOver: true, controllerUid: 'owner', controllerEpoch: 1, players: [{name: 'Owner', factionId: 'frontier'}, {name: 'Peer', factionId: 'brood'}], matchStartedAt: started.startedAt, matchResult: {winnerIdx: 0, reason: 'Every opposing command base fell.', finishedAt: started.startedAt + 120000}};
    await assertFails(api.setDoc(api.doc(peerDb, 'lobbies', room.id, 'chess_starfront', 'state'), finalState));
    await api.setDoc(api.doc(ownerDb, 'lobbies', room.id, 'chess_starfront', 'state'), finalState);
    await assert.rejects(completeCustomMatch({db: peerDb, auth: peerAuth, api}, room.id), {code: 'HOST_ONLY'});
    const finished = await owner.complete(room.id);
    assert.equal(finished.status, 'finished'); assert.equal(finished.turncraftResult.winnerIdx, 0);
    await assertFails(api.setDoc(api.doc(ownerDb, 'lobbies', room.id, 'chess_starfront', 'state'), finalState));
    await assert.rejects(peer.rematch(room.id), {code: 'HOST_ONLY'});
    const copies = await Promise.all([owner.rematch(room.id), owner.rematch(room.id)]);
    assert.equal(copies[0].id, copies[1].id); assert.notEqual(copies[0].id, room.id);
    assert.equal(copies[0].status, 'waiting'); assert.ok(Object.values(copies[0].turncraftPlayers).every(player => !player.ready));
    assert.equal((await peer.get(room.id)).nextLobbyId, copies[0].id);

    const privateRoom = await owner.create({name: 'Private', visibility: 'private'});
    assert.ok(!(await stranger.browse()).lobbies.some(row => row.id === privateRoom.id));
    await assert.rejects(peer.join({lobbyId: privateRoom.id}), {code: 'INVITE_REQUIRED'});
    const raw = (await api.getDoc(api.doc(peerDb, 'lobbies', privateRoom.id))).data();
    assert.equal(raw.inviteCode, undefined);
    await assertFails(api.updateDoc(api.doc(peerDb, 'lobbies', privateRoom.id), {members: {...raw.members, peer: 'Peer'}, players: ['Owner', 'Peer'], turncraftSeats: ['owner', 'peer'], turncraftPlayers: {...raw.turncraftPlayers, peer: {name: 'Peer', factionId: 'ascendant', team: 'ffa', ready: false, avatar: null}}, updatedAt: Date.now()}));
    await peer.join({code: privateRoom.inviteCode});
    await assertSucceeds(api.getDoc(api.doc(peerDb, 'turncraftLobbySecrets', privateRoom.id)));
    await assertFails(api.getDoc(api.doc(strangerDb, 'turncraftLobbyJoins', privateRoom.id, 'members', 'peer')));
    await owner.leave(privateRoom.id);
    assert.equal((await peer.get(privateRoom.id)).hostUid, 'peer');
    await peer.configure(privateRoom.id, {name: 'Transferred Host'});
    assert.equal((await peer.get(privateRoom.id)).name, 'Transferred Host');
    const three = await owner.create({name: 'Three seats', settings: {maxPlayers: 3}});
    await peer.join({lobbyId: three.id}); await stranger.join({lobbyId: three.id});
    const threeRaw = (await api.getDoc(api.doc(peerDb, 'lobbies', three.id))).data();
    const reorderedMembers = {...threeRaw.members}, reorderedPlayers = {...threeRaw.turncraftPlayers};
    delete reorderedMembers.peer; delete reorderedPlayers.peer;
    await assertFails(api.updateDoc(api.doc(peerDb, 'lobbies', three.id), {members: reorderedMembers, turncraftPlayers: reorderedPlayers, turncraftSeats: ['stranger', 'owner'], players: ['Stranger', 'Owner'], hostUid: 'stranger', host: 'Stranger', updatedAt: Date.now()}));
    await peer.leave(three.id);
    assert.deepEqual((await owner.get(three.id)).turncraftSeats, ['owner', 'stranger']);
    assert.equal((await owner.get(three.id)).hostUid, 'owner');
    const saved = (await api.getDoc(api.doc(ownerDb, 'users', 'Owner'))).data();
    assert.equal(saved.gameStats.turncraft.mmr, 1500); assert.equal(saved.gameStats.turncraft.rankedMatches, 10); assert.equal(saved.gameStats.otherGame.wins, 9);
    console.log('Direct Firestore lobby emulator passed: create/join/invites, readiness, frozen host start, controller completion, fresh rematch, host departure and unchanged ratings.');
  } finally {await env.cleanup();}
})().catch(error => {console.error(error); process.exitCode = 1;});
