'use strict';
// Positive end-to-end Firestore contract; may also run against the site's supplied
// permissive users/lobbies rules using GAME_PROFILE_RULES_FILE. Never production.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
const {initializeTestEnvironment} = require('@firebase/rules-unit-testing');
const api = require('firebase/firestore');
const load = file => import(pathToFileURL(path.resolve(__dirname, file)).href);
const storage = () => { const values = new Map(); return {getItem: key => values.get(key) || null, setItem: (key,value) => values.set(key,value), removeItem: key => values.delete(key)}; };

(async () => {
  if (!process.env.FIRESTORE_EMULATOR_HOST) throw new Error('Use a local Firestore demo emulator. Production Firebase is never used.');
  const env = await initializeTestEnvironment({projectId:'demo-profile-compat', firestore:{rules:fs.readFileSync(process.env.GAME_PROFILE_RULES_FILE || path.resolve(__dirname,'../../../firestore.rules'),'utf8')}});
  const clients = [];
  try {
    await env.clearFirestore();
    await env.withSecurityRulesDisabled(async context => {
      for (const name of ['Owner','Peer','Other','Scoped']) await api.setDoc(api.doc(context.firestore(),'users',name),{username:name,bio:'Keep this profile',gameStats:{otherGame:{wins:7}}});
    });
    const ownerDb = env.authenticatedContext('owner').firestore();
    const peerDb = env.authenticatedContext('peer').firestore();
    const reopenedDb = env.authenticatedContext('another-browser').firestore();
    console.log('Checking Faction Forge account restoration and receipts…');
    const {createFirebaseProgress,newSoloProfile,settleSolo} = await load('../../faction-forge/firebase-progress.js');
    const {selectSoloAccount}=await load('../../faction-forge/solo-account.js');
    const {ALL_TROOPS,NEW_TROOPS} = require('../../../server/faction-forge/domain.cjs');
    const troops = Object.fromEntries(ALL_TROOPS.map(key => [key,{unlockable:NEW_TROOPS.includes(key)}]));
    const progress = async (db,uid,name,local=storage()) => {
      const auth={currentUser:{uid}};
      const selection=await selectSoloAccount({db,auth,api,username:name,troops,storage:local});
      assert.deepEqual(selection.profilePath,['users',name,'factionForge','profile']);
      const client=createFirebaseProgress({db,auth,api,username:name,troops,...selection,storage:local}); clients.push(client); return client;
    };
    const legacyReward={id:'already-saved-legacy',mode:'campaign',missionId:'forge-01',won:true,lives:2};
    const legacy=settleSolo(newSoloProfile('owner','Owner',troops),legacyReward);
    await api.setDoc(api.doc(ownerDb,'factionForgeSoloProfiles','owner'),legacy.profile);
    await api.setDoc(api.doc(ownerDb,'factionForgeSoloProfiles','owner','results',legacyReward.id),legacy.receipt);
    const oldQueue=storage();oldQueue.setItem('factionForge.solo.pending.owner',JSON.stringify([legacyReward]));
    const forge = await progress(ownerDb,'owner','Owner',oldQueue);
    await forge.loadProfile();
    assert.equal(forge.profile.wins,1,'migration and queued legacy result reuse the old receipt');
    assert.deepEqual(forge.profile.campaign,legacy.profile.campaign);
    await api.updateDoc(api.doc(ownerDb,'users','Owner','factionForge','profile'),{forgeDust:200,'troops.rifleman.cards':10});
    await forge.setRewardTarget('rifleman');
    const reward={id:'persisted-campaign',mode:'campaign',missionId:'forge-01',won:true,lives:4};
    await forge.recordSoloResult(reward);
    const afterWin = structuredClone(forge.profile);
    await forge.recordSoloResult(reward);
    assert.deepEqual(forge.profile,afterWin,'replaying a campaign reward must not grant it twice');
    await forge.buyPack('vanir',{requestId:'persisted-pack'});
    const afterPack=structuredClone(forge.profile);
    await forge.buyPack('vanir',{requestId:'persisted-pack'});
    assert.deepEqual(forge.profile,afterPack,'replaying a purchase must not spend twice');
    await forge.upgradeTroop('rifleman',{requestId:'persisted-upgrade'});
    const afterUpgrade=structuredClone(forge.profile);
    await forge.upgradeTroop('rifleman',{requestId:'persisted-upgrade'});
    assert.deepEqual(forge.profile,afterUpgrade,'replaying an upgrade must not spend twice');
    await forge.recordSoloRoundWin({id:'persisted-round',mode:'bot',round:1});
    const completeForge=structuredClone(forge.profile);
    await forge.recordSoloRoundWin({id:'persisted-round',mode:'bot',round:1});
    assert.deepEqual(forge.profile,completeForge,'replaying a round must not grant cards twice');
    const reopenedForge=await progress(reopenedDb,'another-browser','Owner');
    await reopenedForge.loadProfile();
    assert.equal(reopenedForge.profile.forgeDust,completeForge.forgeDust);
    assert.deepEqual(reopenedForge.profile.troops,completeForge.troops);
    assert.deepEqual(reopenedForge.profile.campaign,completeForge.campaign);
    assert.equal(reopenedForge.profile.wins,2);
    await reopenedForge.recordSoloResult(reward);
    assert.equal(reopenedForge.profile.wins,2,'new browser must reuse the profile receipt');
    const otherForge=await progress(reopenedDb,'another-browser','Other');
    await otherForge.loadProfile();
    assert.equal(otherForge.profile.forgeDust,0);
    assert.equal(otherForge.profile.wins,0,'another selected profile has its own progress');
    assert.equal((await api.getDoc(api.doc(reopenedDb,'users','Owner','factionForge','profile'))).data().wins,2);
    const scopedLegacy={...newSoloProfile('owner','Scoped',troops),forgeDust:31};
    await env.withSecurityRulesDisabled(async context=>api.setDoc(api.doc(context.firestore(),'factionForgeSoloProfiles','owner','accounts','name-Scoped'),scopedLegacy));
    let scopedAccessible=true;
    try {await api.getDoc(api.doc(ownerDb,'factionForgeSoloProfiles','owner','accounts','name-Scoped'));}
    catch(error) {if(error.code!=='permission-denied')throw error;scopedAccessible=false;}
    const scopedForge=await progress(ownerDb,'owner','Scoped');await scopedForge.loadProfile();
    assert.equal(scopedForge.profile.forgeDust,scopedAccessible?31:0,'optional denied old scoped saves cannot block the canonical account');

    console.log('Checking TurnCraft personal history and checkpoints…');
    const {createProfileStore}=await load('../shattered-front/profile-store.mjs');
    const {MISSIONS}=await load('../shattered-front/campaign.mjs');
    const personal=createProfileStore({db:ownerDb,api});
    const mission={resultId:'persisted-operation',missionId:MISSIONS[0].id,won:true,stars:3,difficulty:'medium',durationSeconds:120};
    await personal.save('Owner','campaign',mission);
    assert.equal((await createProfileStore({db:reopenedDb,api}).save('Owner','campaign',mission)).wrote,false);
    assert.equal((await api.getDoc(api.doc(reopenedDb,'users','Owner','turncraftSoloHistory',mission.resultId))).data().stars,3);
    await api.setDoc(api.doc(ownerDb,'users','Owner','turncraftSaves','active'),{username:'Owner',packed:JSON.stringify({username:'Owner',missionId:MISSIONS[0].id,savedAt:123}),savedAt:123});
    assert.equal(JSON.parse((await api.getDoc(api.doc(reopenedDb,'users','Owner','turncraftSaves','active'))).data().packed).missionId,MISSIONS[0].id);
    await api.setDoc(api.doc(ownerDb,'users','Owner','turncraftSaves','active'),{username:'Owner',packed:null,savedAt:124,completedRunId:mission.resultId});
    assert.equal((await api.getDoc(api.doc(reopenedDb,'users','Owner','turncraftSaves','active'))).data().completedRunId,mission.resultId);

    console.log('Checking TurnCraft ranked lobby and result receipts…');
    const {createLobbyStore}=await load('../shattered-front/lobby-store.mjs');
    const {saveMatchResult}=await load('../shattered-front/result-store.mjs');
    const ownerAuth={currentUser:{uid:'owner'}},peerAuth={currentUser:{uid:'peer'}};
    const owner=createLobbyStore({db:ownerDb,auth:ownerAuth,api,getIdentity:()=>({uid:'owner',username:'Owner'})});
    const peer=createLobbyStore({db:peerDb,auth:peerAuth,api,getIdentity:()=>({uid:'peer',username:'Peer'})});
    const room=await owner.create({requestId:'persisted-ranked',ranked:true,settings:{maxPlayers:4,fillAi:true}});
    assert.equal(room.ranked,true);assert.equal(room.settings.maxPlayers,2);assert.equal(room.settings.fillAi,false);
    await peer.join({lobbyId:room.id});
    await owner.player(room.id,{ready:true});await peer.player(room.id,{ready:true});
    const started=await owner.start(room.id);
    await api.setDoc(api.doc(ownerDb,'users','Owner','turncraftPending',room.id),{lobbyId:room.id,username:'Owner',createdAt:Date.now()});
    await api.setDoc(api.doc(peerDb,'users','Peer','turncraftPending',room.id),{lobbyId:room.id,username:'Peer',createdAt:Date.now()});
    await api.updateDoc(api.doc(ownerDb,'lobbies',room.id),{chessStarfrontController:{ownerUid:'owner',ownerName:'Owner',epoch:1,expiresAtMs:Date.now()+16000},updatedAt:api.serverTimestamp()});
    await api.setDoc(api.doc(peerDb,'lobbies',room.id,'chess_starfront_commands','peer-move'),{by:'Peer',slot:1,type:'move'});
    await api.setDoc(api.doc(ownerDb,'lobbies',room.id,'chess_starfront','state'),{gameKey:'chess_starfront',controllerUid:'owner',controllerEpoch:1,gameOver:true,players:[{name:'Owner',factionId:'frontier',ai:false},{name:'Peer',factionId:'ascendant',ai:false}],matchStartedAt:started.startedAt,matchResult:{winnerIdx:0,reason:'Every opposing command base fell.',finishedAt:started.startedAt+120000}});
    await owner.complete(room.id);
    const inputs={db:ownerDb,auth:ownerAuth,api};
    const duplicate=await Promise.all([saveMatchResult(inputs,room.id,'Owner'),saveMatchResult(inputs,room.id,'Owner')]);
    assert.equal(duplicate.filter(value=>value.wrote).length,1,'concurrent tabs count one ranked result');
    const pendingOnNewBrowser=await api.getDocs(api.collection(reopenedDb,'users','Peer','turncraftPending'));
    assert.deepEqual(pendingOnNewBrowser.docs.map(row=>row.id),[room.id]);
    await saveMatchResult({db:reopenedDb,auth:{currentUser:{uid:'another-browser'}},api},room.id,'Peer');
    const recoveredReceipt=(await api.getDoc(api.doc(reopenedDb,'users','Peer','turncraftHistory',room.id))).data();
    assert.equal(recoveredReceipt.uid,'peer','unclaimed match recovery retains the original participant UID after transport identity changes');
    await api.deleteDoc(api.doc(reopenedDb,'users','Peer','turncraftPending',room.id));
    await api.deleteDoc(api.doc(ownerDb,'users','Owner','turncraftPending',room.id));
    assert.equal((await api.getDocs(api.collection(reopenedDb,'users','Peer','turncraftPending'))).size,0);
    const winner=(await api.getDoc(api.doc(reopenedDb,'users','Owner'))).data();
    const loser=(await api.getDoc(api.doc(peerDb,'users','Peer'))).data();
    assert.equal(winner.gameStats.turncraft.mmr,1025);assert.equal(winner.gameStats.turncraft.rankedWins,1);assert.equal(winner.gameStats.turncraft.multiplayerMatches,1);
    assert.equal(loser.gameStats.turncraft.mmr,975);assert.equal(loser.gameStats.turncraft.rankedLosses,1);
    assert.equal(winner.gameStats.otherGame.wins,7);assert.equal(winner.bio,'Keep this profile');
    assert.equal(winner.gameStats.turncraft.campaign.completedMissions[MISSIONS[0].id].stars,3);
    assert.equal((await api.getDoc(api.doc(reopenedDb,'users','Owner','turncraftHistory',room.id))).data().mode,'ranked');
    assert.equal((await saveMatchResult({db:reopenedDb,auth:{currentUser:{uid:'another-browser'}},api},room.id,'Owner')).wrote,false,'saved history stays idempotent after another browser reopens it');
    const privateRoom=await owner.create({requestId:'persisted-private',visibility:'private'});
    await peer.join({code:privateRoom.inviteCode});
    assert.equal((await peer.get(privateRoom.id)).members.peer,'Peer');
    console.log('Game profile compatibility passed: Faction Forge cross-browser restoration and isolated profiles; immutable reward/purchase/upgrade/round retries; TurnCraft solo history/checkpoints; ranked create/join/play/finish/history/rating once; private invitation. Rules: '+(process.env.GAME_PROFILE_RULES_FILE||'firestore.rules'));
  } finally {for(const client of clients)client.dispose();await env.cleanup();}
})().catch(error=>{console.error(error);process.exitCode=1;});
