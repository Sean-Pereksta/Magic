test('latest-only writer coalesces frames with one outstanding request',async()=>{
  let now=0,resolve;const writes=[];
  const w=new LatestWriter(v=>{writes.push(v);return new Promise(r=>resolve=r);},{now:()=>now});
  w.offer({x:0,z:0,yaw:0});const first=w.flush();await Promise.resolve();
  for(let x=1;x<=100;x++){w.offer({x,z:0,yaw:0});w.flush(true);}
  assert.equal(writes.length,1);resolve();await first;now=1000;
  const second=w.flush();await Promise.resolve();assert.equal(writes.length,2);assert.equal(writes[1].x,100);resolve();await second;
});
test('failed writes do not advance the acknowledged baseline and retry newest data',async()=>{
  let now=0,fail=true;const writes=[];
  const w=new LatestWriter(async v=>{writes.push(v);if(fail)throw new Error('offline');},{now:()=>now});
  w.offer({x:1,z:0,yaw:0});assert.equal(await w.flush(),false);assert.equal(w.last,null);
  w.offer({x:20,z:0,yaw:0});now=100;assert.equal(await w.flush(true),false);assert.equal(writes.length,1);
  now=5000;fail=false;assert.equal(await w.flush(),true);assert.equal(w.last.x,20);
});
test('idle heartbeats are bounded and disposal stops future writes',async()=>{
  let now=0,count=0;const w=new LatestWriter(async()=>count++,{now:()=>now});
  w.offer({x:1,z:1,yaw:0});await w.flush();now=1000;await w.flush();assert.equal(count,1);
  now=2600;await w.flush();assert.equal(count,2);w.close();now=6000;await w.flush(true);assert.equal(count,2);
});
