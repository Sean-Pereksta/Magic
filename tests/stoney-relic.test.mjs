test('demons actually pursue through corridors and never cross walls',()=>{
  const s=state(),m=new Maze(s),from=100,to=m.graph[from][0],target=m.center(to),p=player(target);
  const traps=new Map([['d',trap(m.center(from))]]),players=new Map([['p',p]]);let enemies={};
  for(let frame=0;frame<120;frame++){
    const now=5000+frame*50;p.updatedAt=now;
    const prev=enemies.d;enemies=stepEnemies(m,s,traps,players,enemies,.05,now);
    assert.ok(!m.blocked(enemies.d.x,enemies.d.z,.25));
    if(prev)assert.ok(distance(prev,enemies.d)<=2.65*.05+.001);
  }
  assert.ok(distance(enemies.d,target)<1);assert.equal(enemies.d.targetId,'p');
});
