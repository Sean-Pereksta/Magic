test('spawn director respects living players, crown, entrance, spacing and limits',()=>{
  const s=state(),m=new Maze(s),players=new Map([['p',player(m.center(100))]]),traps=new Map();
  s.crown=m.center(200);const p=chooseSpawn('demon',s,m,players,traps,5000);assert.ok(p);
  assert.equal(placementError('demon',p,s,m,players,traps,5000),'');
  assert.match(placementError('demon',m.center(100),s,m,players,traps,5000),/close|entrance/);
  assert.match(placementError('demon',s.crown,s,m,players,traps,5000),/crown|entrance|close/);
  assert.match(placementError('demon',m.center(m.entry),s,m,players,traps,5000),/entrance/);
  traps.set('one',trap(p));assert.match(placementError('fire',p,s,m,players,traps,5000),/space/);
  assert.match(placementError('crown',p,s,m,players,traps,5000),/cannot be moved/);
});
