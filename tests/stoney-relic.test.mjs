test('seeded maze stays deterministic and all cells are reachable',()=>{
  for(let seed=0;seed<50;seed++){
    const m=new Maze(state(seed));assert.deepEqual(makeMaze(21,21,seed),makeMaze(21,21,seed));
    assert.equal([...m.distances(m.entry)].filter(x=>x>=0).length,441);
    assert.equal(m.graph.reduce((n,x)=>n+x.length,0),880);
  }
});
test('every pathfinding edge is physically traversable; no wall tunnelling',()=>{
  const m=new Maze(state());
  for(let i=0;i<m.cells.length;i++)for(const j of m.graph[i])assert.equal(m.clear(m.center(i),m.center(j),.34),true);
  let checked=0;
  for(let i=0;i<m.cells.length;i++)if(i%21<20&&!m.graph[i].includes(i+1)){
    const a=m.center(i),b=m.center(i+1);assert.equal(m.clear(a,b),false);
    assert.ok(distance(m.move(a,b.x-a.x,b.z-a.z),b)>.5);checked++;
  }
  assert.ok(checked>100);
});
